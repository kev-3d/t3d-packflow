-- PackFlow schema for PostgreSQL, equivalent to the SQLite schema in database.py.
-- Phase 1 keeps the SQLite value formats (ISO dates as TEXT, flags as 0/1 INTEGER,
-- JSON as TEXT) so application code behaves identically on both engines.

CREATE TABLE app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    length_cm DOUBLE PRECISION NOT NULL CHECK (length_cm > 0),
    width_cm DOUBLE PRECISION NOT NULL CHECK (width_cm > 0),
    height_cm DOUBLE PRECISION NOT NULL CHECK (height_cm > 0),
    weight_kg DOUBLE PRECISION NOT NULL CHECK (weight_kg > 0),
    rotation_allowed INTEGER NOT NULL DEFAULT 1,
    fragile INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL,
    capacity_family TEXT NOT NULL DEFAULT ''
);

CREATE TABLE box_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    length_cm DOUBLE PRECISION NOT NULL CHECK (length_cm > 0),
    width_cm DOUBLE PRECISION NOT NULL CHECK (width_cm > 0),
    height_cm DOUBLE PRECISION NOT NULL CHECK (height_cm > 0),
    empty_weight_kg DOUBLE PRECISION NOT NULL CHECK (empty_weight_kg >= 0),
    max_weight_kg DOUBLE PRECISION NOT NULL CHECK (max_weight_kg > 0),
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL,
    capacities TEXT NOT NULL DEFAULT '{}',
    reference_50ml INTEGER,
    reference_250ml INTEGER
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    client TEXT NOT NULL,
    vendor TEXT NOT NULL DEFAULT '',
    order_date TEXT,
    requested_date TEXT,
    currency TEXT NOT NULL DEFAULT 'USD',
    source_filename TEXT,
    source_type TEXT NOT NULL DEFAULT 'pdf',
    delivery_address TEXT NOT NULL DEFAULT '',
    billing_address TEXT NOT NULL DEFAULT '',
    terms TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    subtotal DOUBLE PRECISION NOT NULL DEFAULT 0,
    tax_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'needs_review',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id),
    sku_raw TEXT NOT NULL,
    description TEXT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
    line_number INTEGER,
    requested_date TEXT,
    tax_label TEXT NOT NULL DEFAULT '',
    discount_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
    amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    is_suggested INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE packing_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    box_count INTEGER NOT NULL,
    average_utilization DOUBLE PRECISION NOT NULL,
    total_weight_kg DOUBLE PRECISION NOT NULL,
    result_json TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE source_documents (
    order_id BIGINT PRIMARY KEY REFERENCES orders(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content BYTEA NOT NULL
);

CREATE TABLE analysis_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    plan_id BIGINT UNIQUE REFERENCES packing_plans(id) ON DELETE SET NULL,
    filename TEXT NOT NULL,
    pdf_content BYTEA NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer TEXT NOT NULL,
    phone_number TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    contact_name TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    country TEXT NOT NULL DEFAULT '',
    shipping_address TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE shipping_quotes (
    order_id BIGINT PRIMARY KEY REFERENCES orders(id) ON DELETE CASCADE,
    plan_id BIGINT,
    inputs_json TEXT NOT NULL,
    result_json TEXT NOT NULL,
    tariff_version TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE client_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company TEXT NOT NULL,
    company_key TEXT NOT NULL UNIQUE,
    aliases TEXT NOT NULL DEFAULT '',
    client_id BIGINT REFERENCES clients(id) ON DELETE SET NULL,
    invoice_email TEXT NOT NULL DEFAULT '',
    payment TEXT NOT NULL DEFAULT '',
    pricing_requirements TEXT NOT NULL DEFAULT '',
    docs_required TEXT NOT NULL DEFAULT '',
    courier TEXT NOT NULL DEFAULT '',
    comments TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE UNIQUE INDEX idx_clients_customer ON clients (lower(trim(customer)));
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);
CREATE INDEX idx_plans_order ON packing_plans (order_id, id DESC);
CREATE INDEX idx_reports_order ON analysis_reports (order_id);
CREATE INDEX idx_requirements_client ON client_requirements (client_id);
CREATE INDEX idx_orders_listing ON orders (order_date DESC NULLS LAST, id DESC);
